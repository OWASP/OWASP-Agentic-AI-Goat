CREATE SCHEMA xss;
REVOKE ALL ON SCHEMA xss FROM PUBLIC;
CREATE TABLE xss.profiles (
  user_key text PRIMARY KEY,
  name text NOT NULL DEFAULT 'Security Student',
  bio text NOT NULL DEFAULT 'Learning about web security.',
  website text NOT NULL DEFAULT 'https://example.com',
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE xss.progress (
  user_key text NOT NULL,
  objective_id text NOT NULL,
  completed integer NOT NULL DEFAULT 0 CHECK (completed IN (0,1)),
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(user_key,objective_id)
);
CREATE TABLE xss.emails (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject text NOT NULL,
  sender text NOT NULL,
  body text NOT NULL,
  user_key text,
  received_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
