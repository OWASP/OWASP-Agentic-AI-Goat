-- Separate tables from the canonical XSS exercises, within the same isolated DB.
CREATE TABLE xss.email_profiles (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL UNIQUE,
 full_name text NOT NULL, email_address text NOT NULL,
 company_name text, job_title text, phone_number text,
 signature_html text, signature_plain text, profile_image_url text,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,user_id)
);
CREATE TABLE xss.email_templates (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL, profile_id integer NOT NULL,
 template_name text NOT NULL, subject text, template_type text DEFAULT 'general',
 html_content text NOT NULL, plain_content text, ai_prompt text, ai_model text,
 is_favorite integer NOT NULL DEFAULT 0 CHECK(is_favorite IN(0,1)),
 view_count integer NOT NULL DEFAULT 0, last_viewed timestamptz,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,user_id),
 FOREIGN KEY(profile_id,user_id) REFERENCES xss.email_profiles(id,user_id)
);
CREATE INDEX email_templates_owner ON xss.email_templates(user_id,created_at DESC);
CREATE TABLE xss.template_previews (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 template_id integer NOT NULL, user_id bigint NOT NULL,
 preview_type text DEFAULT 'html', xss_detected integer NOT NULL DEFAULT 0 CHECK(xss_detected IN(0,1)),
 xss_payload text, viewed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(template_id,user_id) REFERENCES xss.email_templates(id,user_id) ON DELETE CASCADE
);
CREATE TABLE xss.xss_challenge_progress (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL, challenge_level integer NOT NULL CHECK(challenge_level BETWEEN 1 AND 4),
 challenge_name text NOT NULL, completed integer NOT NULL DEFAULT 0 CHECK(completed IN(0,1)),
 payload_used text, completed_at timestamptz, hints_used integer NOT NULL DEFAULT 0,
 attempts integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,challenge_level)
);
-- Retain immutable grading metadata after a learner resets/deletes templates.
-- template_id is historical provenance, deliberately not a cascading FK.
CREATE TABLE xss.xss_email_judge_receipts (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL, challenge_level integer NOT NULL CHECK(challenge_level BETWEEN 1 AND 4),
 template_id integer NOT NULL, verdict text NOT NULL CHECK(verdict IN('pass','fail','inconclusive','unavailable')),
 judge_version text, rubric_version text NOT NULL, evidence_digest text,
 run_id text, error_code text, browser_executed integer NOT NULL CHECK(browser_executed IN(0,1)),
 browser_reason text, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX email_judge_owner ON xss.xss_email_judge_receipts(user_id,created_at DESC);
GRANT SELECT,INSERT,UPDATE,DELETE ON xss.email_profiles,xss.email_templates,xss.template_previews,xss.xss_challenge_progress TO dvaia_xss_runtime;
GRANT SELECT,INSERT ON xss.xss_email_judge_receipts TO dvaia_xss_runtime;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA xss TO dvaia_xss_runtime;
