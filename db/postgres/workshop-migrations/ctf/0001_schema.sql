CREATE SCHEMA ctf;
REVOKE ALL ON SCHEMA ctf FROM PUBLIC;
-- ctf.db: CTF config, participants, stages, progress, attempts, leaderboard, adaptive blocklists
CREATE TABLE ctf.ctf_config (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT UNIQUE NOT NULL,
  value TEXT NOT NULL,
  description TEXT,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ctf.ctf_participants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER UNIQUE NOT NULL,
  username TEXT NOT NULL,
  email TEXT,
  team_name TEXT,
  started_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  last_activity TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  is_active INTEGER DEFAULT 1,
  total_completion_time INTEGER DEFAULT 0,
  final_position INTEGER,
  completed_at TIMESTAMPTZ
);

CREATE TABLE ctf.ctf_stages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage_number INTEGER UNIQUE NOT NULL,
  stage_name TEXT NOT NULL,
  stage_description TEXT,
  difficulty_level TEXT DEFAULT 'medium',
  ai_guardian_name TEXT,
  ai_guardian_personality TEXT,
  system_prompt TEXT,
  success_criteria TEXT,
  hints TEXT,
  max_attempts INTEGER DEFAULT -1,
  time_penalty_per_wrong_attempt INTEGER DEFAULT 0,
  is_active INTEGER DEFAULT 1,
  stage_order INTEGER NOT NULL,
  difficulty TEXT DEFAULT 'easy',
  defense_style TEXT DEFAULT '[]',
  adaptive_mode TEXT DEFAULT 'none',
  level_score INTEGER DEFAULT 100,
  time_bonus_seconds INTEGER DEFAULT 300,
  feedback_mode TEXT DEFAULT 'reason',
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ctf.ctf_progress (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL,
  stage_id INTEGER NOT NULL,
  status TEXT DEFAULT 'not_started',
  started_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  completion_time INTEGER,
  attempts_count INTEGER DEFAULT 0,
  successful_attempts INTEGER DEFAULT 0,
  failed_attempts INTEGER DEFAULT 0,
  hints_used INTEGER DEFAULT 0,
  hint_penalty_total INTEGER DEFAULT 0,
  time_penalties INTEGER DEFAULT 0,
  final_payload TEXT,
  techniques_used TEXT DEFAULT '[]',
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (participant_id) REFERENCES ctf.ctf_participants (id) ON DELETE CASCADE,
  FOREIGN KEY (stage_id) REFERENCES ctf.ctf_stages (id) ON DELETE CASCADE,
  UNIQUE(participant_id, stage_id)
);

CREATE TABLE ctf.ctf_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL,
  stage_id INTEGER NOT NULL,
  attempt_number INTEGER NOT NULL,
  payload TEXT NOT NULL,
  ai_response TEXT,
  was_successful INTEGER DEFAULT 0,
  response_time INTEGER,
  technique_tag TEXT,
  technique_confidence DOUBLE PRECISION,
  blocked INTEGER DEFAULT 0,
  block_reason TEXT,
  payload_hash TEXT,
  attempt_timestamp TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  session_id TEXT,
  client_ip TEXT,
  user_agent TEXT,
  FOREIGN KEY (participant_id) REFERENCES ctf.ctf_participants (id) ON DELETE CASCADE,
  FOREIGN KEY (stage_id) REFERENCES ctf.ctf_stages (id) ON DELETE CASCADE
);

CREATE TABLE ctf.ctf_leaderboard (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER UNIQUE NOT NULL,
  username TEXT NOT NULL,
  team_name TEXT,
  total_stages_completed INTEGER DEFAULT 0,
  total_completion_time INTEGER DEFAULT 0,
  average_stage_time DOUBLE PRECISION DEFAULT 0,
  fastest_stage_time INTEGER DEFAULT 0,
  slowest_stage_time INTEGER DEFAULT 0,
  total_attempts INTEGER DEFAULT 0,
  success_rate DOUBLE PRECISION DEFAULT 0,
  total_score INTEGER DEFAULT 0,
  last_updated TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  rank_position INTEGER,
  is_completed INTEGER DEFAULT 0,
  completion_timestamp TIMESTAMPTZ,
  FOREIGN KEY (participant_id) REFERENCES ctf.ctf_participants (id) ON DELETE CASCADE
);

CREATE TABLE ctf.ctf_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL,
  participant_id INTEGER,
  stage_id INTEGER,
  event_data TEXT,
  timestamp TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  is_public INTEGER DEFAULT 1,
  FOREIGN KEY (participant_id) REFERENCES ctf.ctf_participants (id) ON DELETE CASCADE,
  FOREIGN KEY (stage_id) REFERENCES ctf.ctf_stages (id) ON DELETE CASCADE
);

CREATE TABLE ctf.ctf_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL,
  session_token TEXT UNIQUE NOT NULL,
  started_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  last_heartbeat TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  ended_at TIMESTAMPTZ,
  total_active_time INTEGER DEFAULT 0,
  is_active INTEGER DEFAULT 1,
  client_ip TEXT,
  user_agent TEXT,
  FOREIGN KEY (participant_id) REFERENCES ctf.ctf_participants (id) ON DELETE CASCADE
);

-- Adaptive defense: per-user technique memory
CREATE TABLE ctf.ctf_technique_blocklist (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL,
  stage_id INTEGER NOT NULL,
  technique_tag TEXT NOT NULL,
  first_used_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (participant_id) REFERENCES ctf.ctf_participants (id) ON DELETE CASCADE,
  FOREIGN KEY (stage_id) REFERENCES ctf.ctf_stages (id) ON DELETE CASCADE,
  UNIQUE(participant_id, stage_id, technique_tag)
);

-- Adaptive defense: global winning payload memory
CREATE TABLE ctf.ctf_payload_blocklist (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage_id INTEGER NOT NULL,
  payload_hash TEXT NOT NULL,
  normalized_snippet TEXT,
  first_winner_participant_id INTEGER,
  first_won_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  hit_count INTEGER DEFAULT 0,
  FOREIGN KEY (stage_id) REFERENCES ctf.ctf_stages (id) ON DELETE CASCADE,
  FOREIGN KEY (first_winner_participant_id) REFERENCES ctf.ctf_participants (id) ON DELETE SET NULL,
  UNIQUE(stage_id, payload_hash)
);

-- Admin moderation
CREATE TABLE ctf.ctf_bans (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  banned_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  reason TEXT,
  banned_by INTEGER
);

-- Native CTF grading receipts; no workshop objective IDs.
CREATE TABLE ctf.ctf_judgments (
  run_id TEXT PRIMARY KEY,
  attempt_id INTEGER,
  participant_id INTEGER NOT NULL,
  stage_id INTEGER NOT NULL,
  progress_id INTEGER NOT NULL,
  stage_digest TEXT NOT NULL,
  verdict TEXT NOT NULL,
  accepted INTEGER NOT NULL DEFAULT 0,
  metadata TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ctf_judgments_attempt ON ctf.ctf_judgments(attempt_id);

CREATE UNIQUE INDEX ctf_bans_user ON ctf.ctf_bans(user_id);
