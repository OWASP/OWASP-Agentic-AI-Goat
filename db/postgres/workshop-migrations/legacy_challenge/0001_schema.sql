CREATE SCHEMA IF NOT EXISTS legacy_challenge;
CREATE TABLE legacy_challenge.users (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT UNIQUE NOT NULL,
      email TEXT UNIQUE NOT NULL,
      password TEXT NOT NULL,
      role TEXT DEFAULT 'student',
      full_name TEXT,
      created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
      is_active INTEGER DEFAULT 1
);
CREATE TABLE legacy_challenge.products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    price double precision,
    category TEXT,
    image_url TEXT
);
CREATE TABLE legacy_challenge.comments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    content TEXT NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE legacy_challenge.reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    rating INTEGER NOT NULL,
    comment TEXT NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE legacy_challenge.cart (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER DEFAULT 1,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE legacy_challenge.orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    total_amount double precision NOT NULL,
    payment_method TEXT,
    shipping_address TEXT,
    status TEXT DEFAULT 'pending',
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE legacy_challenge.order_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    price double precision NOT NULL
);
CREATE TABLE legacy_challenge.files (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename TEXT NOT NULL,
    original_name TEXT NOT NULL,
    file_path TEXT NOT NULL,
    file_size INTEGER,
    mime_type TEXT,
    uploaded_by INTEGER,
    uploaded_at timestamptz DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE legacy_challenge.ai_conversations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    prompt TEXT NOT NULL,
    response TEXT,
    model_used TEXT DEFAULT 'llama3.1:8b',
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE legacy_challenge.vulnerability_settings (vulnerability_key text PRIMARY KEY, enabled integer NOT NULL DEFAULT 1);
