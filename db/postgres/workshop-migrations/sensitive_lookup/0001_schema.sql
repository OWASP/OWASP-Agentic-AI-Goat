CREATE SCHEMA sensitive_lookup;
REVOKE ALL ON SCHEMA sensitive_lookup FROM PUBLIC;
CREATE TABLE sensitive_lookup.file_references (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reference_key varchar(100) NOT NULL UNIQUE,file_path varchar(500) NOT NULL,description text,
 access_level text NOT NULL DEFAULT 'public' CHECK(access_level IN ('public','restricted','secret','admin')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE sensitive_lookup.chatbot_templates (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 template_name varchar(100) NOT NULL UNIQUE,template_content text NOT NULL,template_path varchar(500),
 ssi_enabled boolean NOT NULL DEFAULT true,category varchar(50),created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE sensitive_lookup.chatbot_config (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 config_key varchar(100) NOT NULL UNIQUE,config_value text NOT NULL,
 config_type text NOT NULL DEFAULT 'setting' CHECK(config_type IN ('path','template','variable','setting')),
 is_sensitive boolean NOT NULL DEFAULT false,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE sensitive_lookup.exploitation_log (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,user_id text NOT NULL,
 user_input text,query_executed text,vulnerability_type varchar(100),file_accessed varchar(500),
 flag_captured text,success boolean NOT NULL DEFAULT false,ip_address varchar(45),user_agent text,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX exploitation_log_owner ON sensitive_lookup.exploitation_log(user_id,created_at DESC);
GRANT USAGE ON SCHEMA sensitive_lookup TO dvaia_sensitive_lookup_runtime;
GRANT SELECT ON sensitive_lookup.file_references,sensitive_lookup.chatbot_templates,sensitive_lookup.chatbot_config TO dvaia_sensitive_lookup_runtime;
GRANT SELECT,INSERT ON sensitive_lookup.exploitation_log TO dvaia_sensitive_lookup_runtime;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA sensitive_lookup TO dvaia_sensitive_lookup_runtime;
