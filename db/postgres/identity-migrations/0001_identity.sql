CREATE SCHEMA identity;
REVOKE ALL ON SCHEMA identity FROM PUBLIC;
CREATE TABLE identity.users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username text UNIQUE NOT NULL CHECK(length(username) BETWEEN 3 AND 50),
 email text UNIQUE NOT NULL, password text NOT NULL CHECK(password ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
 role text NOT NULL DEFAULT 'student' CHECK(role IN ('student','admin','super_admin')),
 admin_level integer NOT NULL DEFAULT 0 CHECK(admin_level BETWEEN 0 AND 2),
 full_name text, phone text, department text, profile_image text,
 email_verified integer NOT NULL DEFAULT 0 CHECK(email_verified IN (0,1)),
 is_active integer NOT NULL DEFAULT 1 CHECK(is_active IN (0,1)),
 account_locked_until timestamptz, login_attempts integer NOT NULL DEFAULT 0 CHECK(login_attempts>=0),
 last_login timestamptz, last_password_change timestamptz NOT NULL DEFAULT now(),
 password_reset_required integer NOT NULL DEFAULT 0 CHECK(password_reset_required IN (0,1)),
 two_factor_enabled integer NOT NULL DEFAULT 0 CHECK(two_factor_enabled IN (0,1)), two_factor_secret text,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 created_by_ip text, last_login_ip text
);
CREATE TABLE identity.admin_permissions (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 admin_id integer NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
 permission_name text NOT NULL CHECK(permission_name IN ('user_management','challenge_management','system_config','view_analytics','manage_progress','send_notifications','export_data','system_logs','database_access')),
 granted_by integer REFERENCES identity.users(id), granted_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz, is_active integer NOT NULL DEFAULT 1 CHECK(is_active IN (0,1)),
 UNIQUE(admin_id,permission_name)
);
CREATE TABLE identity.user_sessions (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
 session_token_hash text UNIQUE NOT NULL CHECK(session_token_hash ~ '^[a-f0-9]{64}$'),
 device_info jsonb NOT NULL DEFAULT '{}', ip_address text, location text,
 is_active integer NOT NULL DEFAULT 1 CHECK(is_active IN (0,1)),
 last_activity timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(), revoked_at timestamptz,
 revoked_by integer REFERENCES identity.users(id), revoke_reason text
);
CREATE INDEX session_owner ON identity.user_sessions(user_id,last_activity DESC);
CREATE INDEX session_cleanup ON identity.user_sessions(expires_at);
CREATE TABLE identity.activity_logs (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer REFERENCES identity.users(id), action_type text NOT NULL,
 action_details jsonb NOT NULL DEFAULT '{}', ip_address text, user_agent text,
 session_id text, risk_level text NOT NULL DEFAULT 'low' CHECK(risk_level IN ('low','medium','high','critical')),
 success integer NOT NULL DEFAULT 1 CHECK(success IN (0,1)), timestamp timestamptz NOT NULL DEFAULT now()
);
GRANT USAGE ON SCHEMA identity TO dvaia_identity_runtime;
GRANT SELECT,INSERT,UPDATE ON identity.users,identity.admin_permissions TO dvaia_identity_runtime;
GRANT SELECT,INSERT,UPDATE,DELETE ON identity.user_sessions TO dvaia_identity_runtime;
GRANT SELECT,INSERT ON identity.activity_logs TO dvaia_identity_runtime;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA identity TO dvaia_identity_runtime;
