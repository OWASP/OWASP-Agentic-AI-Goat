CREATE TABLE identity.email_agent_progress (
  user_key text NOT NULL,
  objective_number integer NOT NULL CHECK(objective_number BETWEEN 1 AND 5),
  completed integer NOT NULL DEFAULT 0 CHECK(completed IN (0,1)),
  user_email text,
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(user_key,objective_number)
);
CREATE TABLE identity.sent_emails_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_key text NOT NULL,
  recipient_email text NOT NULL,
  scenario_type text,
  email_subject text,
  gmail_message_id text,
  sent_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX sent_emails_owner_idx ON identity.sent_emails_log(user_key,sent_at DESC);
GRANT SELECT,INSERT,UPDATE,DELETE ON identity.email_agent_progress,identity.sent_emails_log TO dvaia_identity_runtime;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA identity TO dvaia_identity_runtime;
