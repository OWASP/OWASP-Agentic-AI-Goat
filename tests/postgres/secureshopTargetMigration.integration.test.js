'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { Pool } = require('pg');
const bcrypt = require('bcryptjs');
const { migrate, readMigrations } = require('../../db/postgres/migrate');
const { createXssBoundedMigrationView } = require('../helpers/xssBoundedMigrationView');
const { createIdentityRepository } = require('../../server/database/postgres/identityRepository');
const { createSecureShopLaunchRepository } = require('../../server/database/postgres/secureshopLaunchRepository');

const enabled = process.env.PG_TEST_DISPOSABLE === 'yes' && Boolean(process.env.PG_SECURESHOP_TARGET_TEST_MIGRATION_URL);
test('forward target migration retains existing reservations and backfills immutable owner admission', { skip: !enabled, timeout: 90000 }, async t => {
  assert.equal(process.cwd(), path.resolve(__dirname, '../..'));
  let pair;
  for (const suffix of ['MIGRATION', 'RUNTIME']) {
    const url = new URL(process.env[`PG_SECURESHOP_TARGET_TEST_${suffix}_URL`]);
    assert.equal(url.protocol, 'postgresql:');
    assert.match(url.pathname, /^\/owasp_ai_goat_test_(?:persona_identity_[a-f0-9]{12}|secureshop_target)$/);
    assert.equal(url.hostname, '127.0.0.1');
    assert.equal(url.username, `dvaia_identity_${suffix.toLowerCase()}`);
    assert.equal(url.password, ''); assert.equal(url.search, ''); assert.equal(url.hash, '');
    assert.ok(Number(url.port) > 0 && Number(url.port) <= 65535);
    const currentPair = `${url.host}${url.pathname}`;
    if (pair === undefined) pair = currentPair; else assert.equal(currentPair, pair);
  }
  const migration = new Pool({ connectionString: process.env.PG_SECURESHOP_TARGET_TEST_MIGRATION_URL });
  const pool = new Pool({ connectionString: process.env.PG_SECURESHOP_TARGET_TEST_RUNTIME_URL });
  const original = path.resolve(__dirname, '../../db/postgres/identity-migrations');
  const view = createXssBoundedMigrationView({ identity: 26 });
  const manifest = await readMigrations(original);
  const expected = ceiling => manifest.filter(row => Number(row.name.slice(0, 4)) <= ceiling).map(({ name, checksum }) => ({ name, checksum }));
  const ledger = async () => (await migration.query('SELECT name,checksum FROM dvaia_migrations.ledger ORDER BY name')).rows;
  t.after(async () => { await Promise.all([migration.end(), pool.end()]); });
  assert.equal((await migration.query("SELECT to_regnamespace('identity') AS present")).rows[0].present, null);
  assert.deepEqual(await view.migrate(migration, original), expected(26).map(row => row.name));
  const baselineLedger = await ledger();
  assert.deepEqual(baselineLedger, expected(26));
  assert.deepEqual(await view.migrate(migration, original), []);
  const identity = createIdentityRepository(pool);
  const passwordHash = await bcrypt.hash('synthetic-target-upgrade', 4);
  const user = await identity.createUser({ username: 'target-upgrade', email: 'target@upgrade.invalid', passwordHash });
  const expiry = new Date(Date.now() + 3600000).toISOString();
  const session = await identity.createSession({ userId: user.id, token: randomUUID(), expiresAt: expiry, expectedPasswordHash: passwordHash });
  const scope = { platformOwnerId: user.id, platformSessionId: session.id };
  const launches = createSecureShopLaunchRepository(pool);
  const launch = await launches.issueOrRenew({ ...scope, expiresAt: expiry });
  const targetId = randomUUID();
  await pool.query("INSERT INTO identity.secureshop_target_reservations(target_id,launch_id,generation,target_kind) VALUES($1,$2,1,'files')", [targetId, launch.binding.launchId]);
  view.setCeiling('identity', 27);
  assert.deepEqual(await view.migrate(migration, original), ['0027_secureshop_target_admission.sql']);
  const candidateLedger = await ledger();
  assert.deepEqual(candidateLedger, expected(27));
  assert.deepEqual(candidateLedger.slice(0, baselineLedger.length), baselineLedger);
  const row = (await pool.query('SELECT * FROM identity.secureshop_target_reservations WHERE target_id=$1', [targetId])).rows[0];
  assert.equal(row.original_platform_owner_id, user.id);
  assert.equal(row.launch_id, launch.binding.launchId);
  assert.equal((await launches.reserveFilesTarget({ ...scope, launchId: row.launch_id, expectedGeneration: 1 })).targetId, targetId);
  await assert.rejects(pool.query('UPDATE identity.secureshop_target_reservations SET original_platform_owner_id=999 WHERE target_id=$1', [targetId]), /permission denied/);
  await assert.rejects(pool.query("INSERT INTO identity.secureshop_target_reservations(target_id,launch_id,generation,target_kind,original_platform_owner_id) VALUES($1,$2,2,'files',$3)", [randomUUID(), row.launch_id, user.id]), /binding is invalid/);
  assert.deepEqual(await view.migrate(migration, original), []);
  assert.deepEqual(await ledger(), candidateLedger);
  const reservationSnapshot = async () => (await migration.query('SELECT to_jsonb(t) AS row FROM identity.secureshop_target_reservations t ORDER BY target_id')).rows;
  const beforeTail = await reservationSnapshot();
  assert.deepEqual(await migrate(migration, original), manifest.filter(row => Number(row.name.slice(0, 4)) > 27).map(row => row.name));
  assert.deepEqual(await reservationSnapshot(), beforeTail);
  assert.deepEqual(await ledger(), manifest.map(({ name, checksum }) => ({ name, checksum })));
  assert.deepEqual((await ledger()).slice(0, candidateLedger.length), candidateLedger);
  assert.deepEqual(await migrate(migration, original), []);
  assert.deepEqual(await reservationSnapshot(), beforeTail);
});
